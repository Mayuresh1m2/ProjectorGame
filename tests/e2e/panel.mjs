// Control panel + surfaces: build layouts through the UI, check the output page renders warped surfaces and plays video.
import { resetScene, restoreScene } from './util.mjs';
await resetScene();
import { chromium } from 'playwright';
const base = 'http://localhost:8000', shots = process.env.SHOTS || '/tmp';
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const errors = [];
const watch = (p, n) => { p.on('pageerror', (e) => errors.push(`${n}: ${e}`)); p.on('console', (m) => { if (m.type() === 'error') errors.push(`${n}: ${m.text()}`); }); };
const panel = await browser.newPage({ viewport: { width: 1400, height: 900 } }); watch(panel, 'panel');
const out = await browser.newPage({ viewport: { width: 1280, height: 720 } }); watch(out, 'output');
await out.goto(`${base}/play.html`);
await panel.goto(`${base}/control.html`);
await panel.waitForTimeout(800);
await panel.screenshot({ path: `${shots}/c-connect.png` });
await panel.click('[data-tab=layout]');
await panel.selectOption('#preset', 'wall-door');
await panel.waitForTimeout(1500);
await panel.screenshot({ path: `${shots}/c-layout.png` });
await out.waitForTimeout(500);
await out.screenshot({ path: `${shots}/o-walldoor.png` });
const vids = await out.evaluate(() => [...document.querySelectorAll('video')].map((v) => ({ src: v.src.split('/').pop(), paused: v.paused, t: v.currentTime, err: v.error?.code || 0, size: `${v.videoWidth}x${v.videoHeight}` })));
const surf = await out.evaluate(() => [...document.querySelectorAll('.surface')].map((e) => ({ id: e.dataset.id, transform: e.style.transform.slice(0, 40) })));
console.log(JSON.stringify({ vids, surf }));
await panel.selectOption('#preset', 'grid4');
await panel.waitForTimeout(1500);
await out.screenshot({ path: `${shots}/o-grid4.png` });
await panel.screenshot({ path: `${shots}/c-layout2.png` });
await panel.click('[data-tab=calibrate]'); await panel.waitForTimeout(500); await panel.screenshot({ path: `${shots}/c-calib.png` });
await panel.click('[data-tab=projector]'); await panel.waitForTimeout(300); await panel.screenshot({ path: `${shots}/c-proj.png` });
console.log(JSON.stringify({ errors }));
await browser.close();
await restoreScene();
if (errors.length) process.exit(1);
